import assert from 'node:assert/strict';
import test from 'node:test';
import {randomUUID} from 'node:crypto';
import {createAdminHumanUser,hashAdminHumanSessionToken,reauthenticateAdminHuman} from '../src/admin/admin-human-auth-service.js';
import {totpCodeAt} from '../src/admin/admin-human-crypto.js';
import {InMemoryAdminHumanAuthRepository} from '../src/admin/repositories/in-memory-admin-human-auth-repository.js';
const key=Buffer.alloc(32,13),rateLimitSecret='isolated-pricing-reauthentication-secret-only';
test('pricing reauthentication validates current session, password, unused TOTP and revocation',async()=>{
  const repository=new InMemoryAdminHumanAuthRepository(),now=new Date('2026-10-20T18:00:00Z');
  const created=await createAdminHumanUser({repository,name:'Pricing administrator',email:'pricing@example.invalid',scopes:['pricing:write'],encryptionKey:key,now});
  const token='rn_admin_session_'+'x'.repeat(43),sessionId=randomUUID();
  await repository.createSession({id:sessionId,userId:created.user.id,tokenHash:hashAdminHumanSessionToken(token),expiresAt:new Date(now.getTime()+7200000).toISOString(),createdAt:now.toISOString()});
  const input={repository,headers:{authorization:'Bearer '+token},password:created.initialPassword,totpCode:totpCodeAt(created.totpSecretBase32,now),encryptionKey:key,rateLimitSecret,now};
  await assert.rejects(reauthenticateAdminHuman({...input,headers:{authorization:'Bearer rn_admin_wrong'}}));
  await assert.rejects(reauthenticateAdminHuman({...input,password:'wrong-but-long-password'}));
  await reauthenticateAdminHuman(input);
  await assert.rejects(reauthenticateAdminHuman(input),/MFA novo/);
  await repository.revokeSession(sessionId,now.toISOString());
  await assert.rejects(reauthenticateAdminHuman({...input,now:new Date(now.getTime()+30000)}),/revogada/);
});
test('MFA counter is consumed once across concurrent requests and persistent rate limit caps failures',async()=>{
  const repository=new InMemoryAdminHumanAuthRepository(),now=new Date('2026-10-20T18:00:00Z');
  const created=await createAdminHumanUser({repository,name:'Concurrent administrator',email:'concurrent@example.invalid',scopes:['pricing:write'],encryptionKey:key,now});
  const token='rn_admin_session_'+'y'.repeat(43);
  await repository.createSession({id:randomUUID(),userId:created.user.id,tokenHash:hashAdminHumanSessionToken(token),expiresAt:new Date(now.getTime()+7200000).toISOString(),createdAt:now.toISOString()});
  const input={repository,headers:{authorization:'Bearer '+token},password:created.initialPassword,totpCode:totpCodeAt(created.totpSecretBase32,now),encryptionKey:key,rateLimitSecret,now};
  const attempts=await Promise.allSettled([reauthenticateAdminHuman(input),reauthenticateAdminHuman(input)]);
  assert.equal(attempts.filter(r=>r.status==='fulfilled').length,1);
  for(let i=0;i<3;i++)await assert.rejects(reauthenticateAdminHuman({...input,password:'incorrect-password-long'}));
  await assert.rejects(reauthenticateAdminHuman(input),e=>(e as {code:string}).code==='ADMIN_LOGIN_RATE_LIMITED');
});
